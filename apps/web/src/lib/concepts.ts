/**
 * Concept glossary — beginner-friendly Mongolian explanations for the concept
 * slugs that lessons tag themselves with. Rendered as interactive cards in the
 * lesson instruction pane so a student can see, per concept: WHAT it is, WHY we
 * use it here, and a tiny EXAMPLE.
 *
 * This module is imported only from the server content service, so the full map
 * never ships to the browser — `resolveConcepts` picks out just the current
 * lesson's entries, and only those serialize into the page.
 *
 * Not every slug has an entry (there are ~300 across the course). A slug with no
 * entry simply renders as a plain tag with no card — add entries over time.
 */

export interface ConceptNote {
  /** Display term, e.g. "<h1>" or "flexbox". */
  term: string;
  /** One line: what it is. */
  what: string;
  /** Why we reach for it — the part students most want answered. */
  why: string;
  /** A plain, everyday-life analogy so an absolute beginner gets it. */
  analogy?: string;
  /** A tiny illustrative snippet (optional). */
  example?: string;
}

export interface ResolvedConcept extends ConceptNote {
  slug: string;
  /** Optional schematic diagram kind rendered in the card (see ConceptDiagram). */
  diagram?: string;
}

