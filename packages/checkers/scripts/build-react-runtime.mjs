// Bundles React + ReactDOM into one IIFE exposing window.React / window.ReactDOM,
// inlined into the preview so React lessons need no CDN, network or server.
import { build } from "esbuild";
import { mkdirSync, writeFileSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const entry = join(root, ".react-entry.tmp.js");
writeFileSync(
  entry,
  `import * as React from "react";
import * as ReactDOMClient from "react-dom/client";
window.React = React;
window.ReactDOM = ReactDOMClient;`,
);

try {
  const out = await build({
    entryPoints: [entry],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "es2020",
    minify: true,
    write: false,
    define: { "process.env.NODE_ENV": '"production"' },
  });
  const code = out.outputFiles[0].text;
  writeFileSync(
    join(root, "src/react-runtime.generated.ts"),
    `// GENERATED by scripts/build-react-runtime.mjs — do not edit.\nexport const REACT_RUNTIME_JS: string = ${JSON.stringify(code)};\nexport const REACT_RUNTIME_BYTES = ${Buffer.byteLength(code)};\n`,
  );
  // Also emit it as a plain asset: the web app serves this file so the browser
  // can fetch React on demand instead of carrying it in every page bundle.
  mkdirSync(join(root, "runtime"), { recursive: true });
  writeFileSync(join(root, "runtime/react-runtime.js"), code);

  console.log(`✓ react runtime: ${(Buffer.byteLength(code) / 1024).toFixed(0)} KB`);
} finally {
  rmSync(entry, { force: true });
}
