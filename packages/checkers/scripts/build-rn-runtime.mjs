// Bundles the hand-written React Native → DOM teaching shim (rn-runtime.src.js)
// into one minified IIFE exposing window.ReactNative / window.Expo / etc., then
// writes it both as a TS constant (server grader inlines it) and as a public
// asset the browser preview fetches on demand — exactly like the React runtime.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(root, "../..");
const entry = join(root, "scripts/rn-runtime.src.js");

const out = await build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  write: false,
});
const code = out.outputFiles[0].text;

writeFileSync(
  join(root, "src/rn-runtime.generated.ts"),
  `// GENERATED by scripts/build-rn-runtime.mjs — do not edit.\nexport const RN_RUNTIME_JS: string = ${JSON.stringify(code)};\nexport const RN_RUNTIME_BYTES = ${Buffer.byteLength(code)};\n`,
);
writeFileSync(join(repoRoot, "apps/web/public/lib/rn-runtime.js"), code);

console.log(`✓ react-native shim: ${(Buffer.byteLength(code) / 1024).toFixed(1)} KB`);
